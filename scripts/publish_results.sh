#!/usr/bin/env bash
# Run the evaluations on this machine and publish the results to GitHub.
#   scripts/publish_results.sh                 # ingest if the DB is empty, retrieval eval + local RAGAS (Ollama)
#   JUDGE=anthropic scripts/publish_results.sh # answers and grading by Claude instead (costs API credits)
#   BENCH=1 scripts/publish_results.sh         # also the Ollama / vLLM / Claude latency benchmark
#   SKIP_RUN=1 scripts/publish_results.sh      # just commit results already on disk
set -euo pipefail
cd "$(dirname "$0")/.."
JUDGE="${JUDGE:-ollama}"
if [ "${SKIP_RUN:-0}" != 1 ]; then
  if ! filings-rag ask "ping" >/dev/null 2>&1 || [ "$(python -c "
from filings_rag.config import get_settings; from filings_rag.db import connect, list_filings
print(len(list_filings(connect(get_settings().database_url))))" 2>/dev/null || echo 0)" = 0 ]; then
    echo "No filings indexed yet: ingesting the demo companies."
    filings-rag ingest
  fi
  filings-rag eval --llm "$JUDGE" --judge "$JUDGE"
  if [ "${BENCH:-0}" = 1 ]; then
    python -m benchmarks.llm_latency --providers ollama vllm anthropic --runs 10 || echo "benchmark skipped a provider"
  fi
fi
if [ -z "$(git status --porcelain evals/results benchmarks/results)" ]; then
  echo "No new results to publish."; exit 0
fi
git add evals/results benchmarks/results
git commit -m "Evaluation results: $(date +%Y-%m-%d)" -m "Generated by scripts/publish_results.sh from real runs (judge: $JUDGE)."
git pull --rebase origin main
git push origin main
echo "Published. The deployed demo's Evaluations tab picks these up on its next deploy."
